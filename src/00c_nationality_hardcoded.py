def wiki_nationality(name):
    try:
        r = SESSION.get("https://en.wikipedia.org/w/api.php",
            params={"action":"query","list":"search",
                    "srsearch":f"{name} footballer","srlimit":1,"format":"json"},
            timeout=10)
        hits = r.json().get("query",{}).get("search",[])
        if not hits: return None
        title = hits[0]["title"]
        r2 = SESSION.get("https://en.wikipedia.org/w/api.php",
            params={"action":"query","titles":title,"prop":"categories",
                    "clshow":"!hidden","cllimit":50,"format":"json"},
            timeout=10)
        pages = r2.json().get("query",{}).get("pages",{})
        cats = []
        for pg in pages.values():
            cats += [c["title"].lower().replace("category:","")
                     for c in pg.get("categories",[])]
        for cat in cats:
            if cat in CAT_MAP:
                return CAT_MAP[cat]
        return None
    except Exception:
        return None

